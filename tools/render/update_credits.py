r"""
Rewrite the rendered-assets block of CREDITS.md from the render manifest.

CREDITS.md is the project's asset SBOM: every file under public/assets gets a
line in the form `filename | source URL | author | licence`. The render
pipeline produces a lot of files, so rather than typing those lines by hand
this script regenerates the block between the two marker comments

    <!-- rendered-assets:start -->
    <!-- rendered-assets:end -->

from public/assets/rendered/manifest.json. Run it after every render, in the
same commit as the new PNGs:

  python tools/render/update_credits.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
CREDITS = REPO / "CREDITS.md"
MANIFEST = REPO / "public" / "assets" / "rendered" / "manifest.json"
SOURCES = HERE / "sources.json"
START = "<!-- rendered-assets:start -->"
END = "<!-- rendered-assets:end -->"


def block() -> str:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    lines = [START, "", "### Phase 24 rendered world, from tools/render", ""]
    lines += [
        "Every file in public/assets/rendered/ is produced by the Blender pipeline in",
        "tools/render/ (see tools/render/README.md) from the CC0 sources below, and is",
        "listed in public/assets/rendered/manifest.json with its full provenance. Each",
        "asset ships as a colour PNG and a `_n.png` normal map; both come from the same",
        "source, so one line covers the pair. This block is generated by",
        "tools/render/update_credits.py, so edit the manifest or sources.json, not this text.",
        "",
        "Source packs:",
        "",
    ]
    for kit in sources["kenney_kits"]:
        lines.append(f"- {kit['name']} | {kit['url']} | {kit['author']} | {kit['licence']}")
    meta = sources["ambientcg_licence"]
    for texture in sources["ambientcg_textures"]:
        lines.append(f"- ambientCG {texture['id']} | {meta['page_pattern'].format(id=texture['id'])} | {meta['author']} | {meta['licence']}")
    lines += ["", "Rendered files:", ""]
    for entry in sorted(manifest["assets"], key=lambda e: e["file"]):
        source = entry["source"]
        lines.append(f"- public/assets/rendered/{entry['file']} (+ normal map) | {source['pack']}, {source['model']} | {source['pack_url']} | {source['author']} | {source['licence']}")
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    text = CREDITS.read_text(encoding="utf-8")
    new_block = block()
    if START in text and END in text:
        before = text[: text.index(START)]
        after = text[text.index(END) + len(END) :]
        text = before + new_block + after
    else:
        # First run: insert the block before the Audio section.
        marker = "\n## Audio"
        if marker not in text:
            print("CREDITS.md has no '## Audio' heading to insert before; add the markers by hand")
            return 1
        text = text.replace(marker, "\n" + new_block + "\n" + marker, 1)
    CREDITS.write_text(text, encoding="utf-8")
    print(f"CREDITS.md updated with {len(json.loads(MANIFEST.read_text(encoding='utf-8'))['assets'])} rendered assets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
